"""Does positive news sentiment identify stocks worth buying?

End-to-end pipeline:
  headlines -> company tickers -> sentiment (VADER / FinBERT) -> price data
  -> event study, market lead/lag, trading backtest, text classifier, stock screen

Usage:
    python run_analysis.py                      # VADER + FinBERT (FinBERT needs torch)
    python run_analysis.py --models vader       # fast, no deep-learning deps
    python run_analysis.py --hold 10            # change the backtest holding period
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

import pandas as pd

from src import analysis as A
from src import plots
from src.data import load_headlines
from src.entities import explode_mentions, tickers
from src.prices import load_prices
from src.sentiment import score

OUT = Path(__file__).resolve().parent / "results"
LABEL = {"vader": "VADER", "finbert": "FinBERT"}


def fmt_pct(x, d=1):
    return f"{x * 100:+.{d}f}%"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    default = ["vader", "finbert"] if importlib.util.find_spec("transformers") else ["vader"]
    ap.add_argument("--models", nargs="+", default=default, choices=["vader", "finbert"])
    ap.add_argument("--hold", type=int, default=5, help="backtest holding period in trading days")
    ap.add_argument("--screen-date", default="2020-07-17", help="as-of date for the sentiment stock screen")
    args = ap.parse_args()
    (OUT / "figures").mkdir(parents=True, exist_ok=True)

    print("1/6 loading headlines")
    heads = load_headlines()
    for m in args.models:
        print(f"2/6 scoring sentiment with {LABEL[m]}")
        heads[m] = score(heads["text"], m)
    heads.to_csv(OUT / "headlines_scored.csv.gz", index=False, compression="gzip")

    print("3/6 linking headlines to companies")
    mentions = explode_mentions(heads)
    print(f"     {len(heads):,} headlines, {len(mentions):,} company mentions, "
          f"{mentions['ticker'].nunique()} companies")

    print("4/6 downloading prices")
    px = load_prices(tickers())

    print("5/6 running analyses")
    md: list[str] = [f"# Results (generated by `run_analysis.py`, hold = {args.hold} days)\n"]
    md.append(f"* Headlines: {len(heads):,} ({heads['date'].min().date()} to {heads['date'].max().date()})")
    md.append(f"* Company mentions: {len(mentions):,} across {mentions['ticker'].nunique()} tickers\n")

    lead_lag, cars = {}, {}
    for m in args.models:
        L = LABEL[m]
        ev = A.build_events(mentions, px, m)
        ev.to_csv(OUT / f"events_{m}.csv", index=False)

        es = A.event_study_table(ev)
        es.to_csv(OUT / f"event_study_{m}.csv", index=False)
        cars[L] = A.car_paths(ev, px)
        lead_lag[L] = A.market_lead_lag(heads, px, m)
        lead_lag[L].to_csv(OUT / f"market_lead_lag_{m}.csv", index=False)

        rets, holdings = A.backtest(ev, px, hold=args.hold)
        perf = A.perf_table(rets, holdings)
        gross = A.perf_table(A.backtest(ev, px, hold=args.hold, cost_bps=0)[0])
        perf.insert(1, "sharpe_gross", gross["sharpe"].to_numpy())
        perf.insert(2, "alpha_ann_gross", gross["alpha_ann"].to_numpy())
        perf.to_csv(OUT / f"backtest_{m}.csv", index=False)
        yearly = A.yearly_sharpe(rets)
        yearly.to_csv(OUT / f"backtest_yearly_sharpe_{m}.csv")
        plots.equity_curves(rets, OUT / "figures" / f"backtest_{m}.png",
                            f"Buying stocks after {L}-positive headlines ({args.hold}-day hold)")

        clf = A.text_classifier(mentions, ev, m)
        clf.to_csv(OUT / f"text_classifier_{m}.csv", index=False)

        scr = A.sentiment_screen(ev, px, args.screen_date)
        scr.to_csv(OUT / f"screen_{m}.csv")

        # ---- markdown report
        md.append(f"## {L}\n")
        md.append(f"Events (ticker x news-day): {len(ev):,} - "
                  + ", ".join(f"{b}: {(ev['bucket'] == b).sum():,}" for b in ["positive", "neutral", "negative"]))
        md.append("\n### Event study: mean market-adjusted return (bps), t-stat clustered by date\n")
        piv = es.pivot(index="bucket", columns="window", values="mean_bps").round(1)
        tst = es.pivot(index="bucket", columns="window", values="t").round(2)
        cols = ["ar_reaction"] + [f"ar_fwd_{h}d" for h in A.HORIZONS]
        tab = piv[cols].astype(str) + " (t=" + tst[cols].astype(str) + ")"
        md.append(tab.loc[["positive", "neutral", "negative", "pos - neg"]].to_markdown())
        md.append("\n### Backtest\n")
        show = perf.copy()
        for c in ["alpha_ann_gross", "total_return", "cagr", "ann_vol", "max_drawdown", "alpha_ann", "pct_days_invested"]:
            show[c] = show[c].map(lambda v: "" if pd.isna(v) else f"{v * 100:.1f}%")
        for c in ["sharpe_gross", "sharpe", "beta", "alpha_t", "avg_holdings"]:
            show[c] = show[c].map(lambda v: "" if pd.isna(v) else f"{v:.2f}")
        md.append(show.set_index("strategy").to_markdown())
        md.append("\nSharpe ratio by calendar year:\n")
        md.append(yearly.round(2).to_markdown())
        md.append("\n### Text classifier (chronological 70/30 split)\n")
        md.append(clf.pivot(index="model", columns="target", values="accuracy").round(3).to_markdown())
        md.append("\nROC AUC:\n")
        md.append(clf.pivot(index="model", columns="target", values="auc").round(3).to_markdown())
        md.append(f"\n### Screen as of {args.screen_date} -> entry {scr.attrs.get('entry')}, exit {scr.attrs.get('exit')}\n")
        s2 = scr.copy()
        s2["sentiment"] = s2["sentiment"].round(3)
        s2["fwd_return"] = s2["fwd_return"].map(fmt_pct)
        s2["fwd_excess_vs_spy"] = s2["fwd_excess_vs_spy"].map(fmt_pct)
        md.append(s2.to_markdown())
        md.append("")

    md.insert(3, "## Market-level lead/lag (corr of daily mean sentiment with SPY return)\n")
    ll = pd.concat({k: v.set_index("lag")[["corr", "t"]] for k, v in lead_lag.items()}, axis=1).round(3)
    md.insert(4, ll.to_markdown() + "\n")

    print("6/6 drawing figures")
    plots.lead_lag(lead_lag, OUT / "figures" / "market_lead_lag.png")
    plots.car_plot(cars, OUT / "figures" / "event_study_car.png")
    main_model = args.models[-1]
    plots.market_sentiment(A.daily_market_sentiment(heads, main_model), px["close"]["SPY"].loc["2018-01-01":"2020-07-31"],
                           OUT / "figures" / "market_sentiment.png", LABEL[main_model])

    (OUT / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"done -> {OUT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
